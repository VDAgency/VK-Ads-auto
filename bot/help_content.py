from typing import Final

# Контакт для вопросов по боту. Один на весь справочник — меняется в одном месте.
SUPPORT_CONTACT: Final = "@CryptoSamara"


@dataclass(frozen=True, slots=True)
class HelpPage:
    """Страница справочника: заголовок и тело (HTML)."""

    title: str
    body: str


@dataclass(frozen=True, slots=True)
class HelpSection:
    """Раздел справочника: подпись для меню и страницы внутри.

    `key` — короткий латинский ключ, попадает в callback_data (`^[a-z0-9_]{1,12}$`).
    """

    key: str
    icon: str
    title: str
    pages: tuple[HelpPage, ...]

    @property
    def label(self) -> str:
        """Подпись кнопки в меню разделов."""
        return f"{self.icon} {self.title}"


