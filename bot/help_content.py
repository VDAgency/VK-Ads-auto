"""Содержимое справочника `/help`: разделы и страницы (только текст, HTML).

Это канальный контент Telegram-бота (HTML-разметка, названия команд, эмодзи), а не
бизнес-логика, поэтому живёт в `bot/`, а не в `services/` (CLAUDE.md §1.3). Логика
листания — в `bot/handlers/help.py`; здесь только данные и чистые функции доступа.

Страницы статичны и ничего не спрашивают у ядра: справка должна открываться и тогда,
когда сервис недоступен, а её длину нужно проверять тестом на этапе CI.

ПРАВИЛО ВЁРСТКИ: каждый HTML-тег открывается и закрывается в пределах ОДНОЙ строки.
Это позволяет безопасно обрезать слишком длинную страницу по границе строки, не
разорвав разметку (`_clip` в хендлере). Проверяется тестом.

Развёрнутая версия этого справочника — `docs/BOT_MANUAL.md`.
"""

