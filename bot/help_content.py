_BY_KEY: Final[dict[str, HelpSection]] = {section.key: section for section in SECTIONS}


def find_section(key: str) -> HelpSection | None:
    """Раздел по ключу. `None` — раздела нет (карточка от прошлой версии справки)."""
    return _BY_KEY.get(key)


def next_section(key: str) -> HelpSection | None:
    """Следующий раздел по порядку. `None` — раздел последний или неизвестен."""
    for index, section in enumerate(SECTIONS):
        if section.key == key:
            return SECTIONS[index + 1] if index + 1 < len(SECTIONS) else None
    return None


def menu_items() -> list[tuple[str, str]]:
    """Пункты меню разделов: `(ключ, подпись)` — вход для клавиатуры."""
    return [(section.key, section.label) for section in SECTIONS]


def total_pages() -> int:
    """Сколько всего страниц в справочнике (для шапки меню)."""
    return sum(len(section.pages) for section in SECTIONS)
