/**
 * Цели рекламы, предлагаемые клиенту в брифе, и флаг их доступности.
 *
 * Единственная точка правды по тому, какие цели уже можно выбрать. Система
 * запускает пока только «подписчики» (`services/brief_parser.Goal`), поэтому
 * остальные цели показаны в форме заблокированными карточками с пометкой
 * «скоро» — клиент видит дорожную карту, но не может выбрать то, что мы ещё
 * не умеем запускать.
 *
 * КАК ВКЛЮЧИТЬ ЦЕЛЬ: когда логика запуска цели готова, здесь меняется
 * `enabled: false` → `true`, и вариант становится доступен. Ничего больше в
 * форме править не нужно. Список задач по целям — docs/ROADMAP.md.
 *
 * Заблокированные варианты рендерятся с атрибутом `disabled`, поэтому не
 * попадают в `FormData` и физически не могут уехать в ядро.
 */
export type BriefGoalOption = {
  /** Значение, уходящее в payload брифа (ключ поля — `goal`). */
  value: string;
  label: string;
  /** false → карточка заблокирована и помечена «скоро». */
  enabled: boolean;
};

export const BRIEF_GOALS: BriefGoalOption[] = [
  { value: "подписчики", label: "Подписчики", enabled: true },
  { value: "сообщения в сообщество", label: "Сообщения в сообщество", enabled: false },
  { value: "заявки — лид-форма", label: "Заявки — лид-форма", enabled: false },
  { value: "заявка через Senler", label: "Заявка через Senler", enabled: false },
  { value: "трафик на сайт", label: "Трафик на сайт", enabled: false },
];

/** Значение цели по умолчанию — единственная доступная сейчас. */
export const DEFAULT_GOAL = BRIEF_GOALS.find((goal) => goal.enabled)?.value ?? "";
