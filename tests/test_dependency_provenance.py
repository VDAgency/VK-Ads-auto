"""Происхождение зависимостей: пакеты берутся с pypi.org и ниоткуда больше.

Почему это тест, а не договорённость. На локальной машине pypi.org закрыт VPN, и
рабочий обход — зеркало (`UV_INDEX_URL=https://mirrors.aliyun.com/pypi/simple/`,
см. заметку `project-pypi-mirror-workaround`). Обход безобидный, пока живёт в
переменной окружения. Но `uv lock`, запущенный с этой переменной, переписывает
адрес источника ВСЕМ пакетам прямо в `uv.lock` — 2026-09-01 так и произошло: 509
записей уехали на зеркало, файл попал в коммит, и прод-образ пересобрался,
скачивая пакеты со стороннего хоста.

Содержимое тогда не пострадало (версии и sha256 всех незатронутых пакетов
совпали с прежними до символа — зеркало оказалось точным прокси), но полагаться
на это нельзя: источник правды для CI и прод-сборки обязан быть официальным.

Правильный приём: зеркало задавать переменной окружения для `uv sync` на этой
машине, а после любого `uv lock` — сверяться с этим тестом.
"""

from __future__ import annotations

import re
from pathlib import Path

_LOCK = Path(__file__).resolve().parent.parent / "uv.lock"

# Официальные хосты: индекс пакетов и хранилище артефактов.
_ALLOWED_HOSTS = frozenset({"pypi.org", "files.pythonhosted.org"})


def _hosts_in_lock() -> set[str]:
    text = _LOCK.read_text(encoding="utf-8")
    return set(re.findall(r'(?:registry|url) = "https://([^/"]+)', text))


def test_lockfile_resolves_only_from_official_pypi() -> None:
    foreign = _hosts_in_lock() - _ALLOWED_HOSTS

    assert not foreign, (
        f"В uv.lock попали сторонние хосты: {sorted(foreign)}. "
        "Скорее всего, `uv lock` запустили с UV_INDEX_URL зеркала — тогда адрес "
        "источника переписывается всем пакетам сразу, и CI с прод-сборкой начинают "
        "тянуть зависимости оттуда же. Зеркало допустимо только для `uv sync` на "
        "локальной машине, через переменную окружения."
    )


def test_lockfile_actually_declares_sources() -> None:
    """Страховка от того, что регулярка перестанет что-либо находить.

    Без этой проверки тест выше молча зазеленеет на пустом множестве, если формат
    `uv.lock` изменится, — и сторож перестанет сторожить.
    """
    assert _hosts_in_lock(), "В uv.lock не нашлось ни одного источника — проверка сломана."
